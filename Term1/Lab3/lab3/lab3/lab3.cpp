#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <windows.h>
#include <cmath>
using namespace std;

int main(void)
{
    SetConsoleCP(1251);
    SetConsoleOutputCP(1251);

    double x, y;

    printf("Введіть координату x > ");
    if (scanf("%lf", &x) != 1) {
		printf("Некоректне введення координати x\n");
		return 1;
    }

    printf("Введіть координату y > ");
    if (scanf("%lf", &y) != 1) {
		printf("Некоректне введення координати y\n");
		return 1;
    }

    printf("x = %6.3lf; y = %6.3lf\n", x, y);

    if ((x * x + y * y <= 1) && (y >= 0 || x >= 0))
        printf("Точка потрапляє в задану область\n");
    else
        printf("Точка не потрапляє в задану область\n");

    return 0;
}




