#include <iostream>
#include <iomanip>
using namespace std;

int main()
{
    const int N = 9;
    int a[N][N] = { 0 };
    int k = 1;

    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {

            if ((i >= j) && (j <= N - 1 - i)) {
                a[i][j] = k++;
            }
            else if ((i <= j) && (j >= N - 1 - i)) {
                a[i][j] = k++;
            }
        }
    }

    for (int i = 0; i < N; i++) {
        for (int j = 0; j < N; j++) {
            cout << a[i][j] << "\t";
        }
        cout << "\n";
    }

    return 0;
}

